  BOS.t = function (key, vars) {
    // Если надписи нет на выбранном языке, берём английскую, потом русскую.
    let text = (STRINGS[BOS.state.lang] || {})[key] ?? STRINGS.en[key] ?? STRINGS.ru[key] ?? key;
    for (const [name, value] of Object.entries(vars || {})) {
      text = text.replace(`{${name}}`, value);
    }
    return text;
  };

  BOS.applyI18nTo = function (el) {
    if (el.dataset.i18n) el.textContent = BOS.t(el.dataset.i18n, el.i18nVars);
    if (el.dataset.i18nPh) el.placeholder = BOS.t(el.dataset.i18nPh);
    if (el.dataset.i18nTitle) {
      el.title = BOS.t(el.dataset.i18nTitle);
      el.setAttribute('aria-label', el.title);
    }
  };

  BOS.applyI18n = function (root) {
    root.querySelectorAll('[data-i18n],[data-i18n-ph],[data-i18n-title]').forEach(BOS.applyI18nTo);
  };
